import {describe,it} from 'node:test';
import assert from 'node:assert/strict';
import {
  auditPhase67IssuerCalendarCrosscheck,
  type Phase67Report
} from '../../server/engine/ema15m/adaptivePhase67IssuerCalendarCrosscheck.js';
import {makePhase67SyntheticIssuerCrosscheckFixture}
  from './phase67_synthetic_issuer_calendar_fixture.js';

type F=ReturnType<typeof makePhase67SyntheticIssuerCrosscheckFixture>;
const fixture=makePhase67SyntheticIssuerCrosscheckFixture;
const audit=(f:F)=>auditPhase67IssuerCalendarCrosscheck(f.input,f.pins);
function noAuthentication(r:Phase67Report){
  assert.equal(r.independentlyAuthenticatedExchangeMasterIssuer,false);
  assert.equal(r.independentlyAuthenticatedExchangeCalendarIssuer,false);
  assert.equal(r.independentlyVerifiedVendorHistoricalL1Entitlement,false);
  assert.equal(r.contemporaneousSourceArrivalClockTrusted,false);
  assert.equal(r.historicalArchiveProvesPastClientReceipt,false);
  assert.equal(r.expiryOrLotClaimIsOfficialExchangeTruth,false);
  assert.equal(r.sourceQuotesAreActualExecutableBrokerFills,false);
  assert.equal(r.statisticalMultiregimeOosProfitabilityVerified,false);
  assert.equal(r.genuineIvThetaGapRiskCalibrated,false);
  assert.equal(r.bestOptionDurationAuthorized,false);
  assert.equal(r.nativeNrmlBrokerStopGttAckVerified,false);
  assert.equal(r.executionAuthorized,false);
  assert.equal(r.productionSafe,false);
  assert.equal(r.nativeOrderInstruction,null);
  assert.ok(!JSON.stringify(r).includes('VENDOR_CANDIDATE_'));
  assert.ok(!JSON.stringify(r).includes('MOCK NOT A REAL'));
}
function rejects(f:F,reason:string,
  status:Phase67Report['status']='INCOMPLETE_EVIDENCE'){
  const r=audit(f);noAuthentication(r);
  assert.equal(r.status,status,JSON.stringify(r));
  assert.ok(r.reasonCodes.includes(reason),JSON.stringify(r));
  return r;
}
describe('Phase67 separate purported issuer OOS contract/expiry/calendar crosscheck',()=>{
  it('all 32 originally listed CE/PE contracts, 4 NO_ENTRY-or-entry OOS dates and 448 native quotes reconcile with a SECOND synthetic source only',()=>{
    const f=fixture(),r=audit(f);noAuthentication(r);
    assert.equal(r.status,'DESCRIPTIVE_CROSS_SOURCE_MATCH_UNVERIFIED_ONLY',
      JSON.stringify(r));
    assert.equal(r.phase66Status,
      'DESCRIPTIVE_OWNER_CANDIDATE_SOURCE_COVERAGE_UNVERIFIED');
    assert.equal(r.syntheticDataset,true);
    assert.equal(r.originalOosDecisions,4);
    assert.equal(r.originalAllListedCePeContractPairs,32);
    assert.equal(r.matchedOriginalDecisionTimeIssuerSnapshots,4);
    assert.equal(r.matchedOriginalCePeContractPairs,32);
    assert.equal(r.distinctListedOriginalInstruments,32);
    assert.equal(r.originalSourceQuotesConfinedToClaimedIssuerSessions,448);
    assert.equal(r.originalQuotesBeyondClaimedLastTradableSession,0);
    assert.equal(r.originalOosNextOpenSessionsMatched,4);
    assert.equal(r.sourceCandidateMasterAndCalendarConsistent,true);
    assert.ok(r.candidateIssuerSessions>=6);
  });
  it('a claimed matching exchange master generated by the same operator can never establish official listing or legal entitlement',()=>{
    const f=fixture(),r=audit(f);noAuthentication(r);
    assert.ok(r.externalBlockers.some(x=>x.includes('ISSUER')));
    assert.equal(r.expiryOrLotClaimIsOfficialExchangeTruth,false);
  });
  it('one native purported issuer-master byte changed without its independently pinned SHA fails immediately',()=>{
    const f=fixture();
    const b=Buffer.from(f.input.candidateIssuerMasterBase64,'base64');
    b[0]^=1;f.input.candidateIssuerMasterBase64=b.toString('base64');
    rejects(f,'PHASE67_CANDIDATE_ISSUER_OR_CALENDAR_BYTES_CHANGED',
      'INVALID_EVIDENCE');
  });
  it('operator-rehashed issuer lot-size change cannot amend original OOS listing',()=>{
    const f=fixture();
    f.issuerMaster.snapshots[0].optionContracts[0].lotSize+=25;
    f.updateMaster();f.repin();
    rejects(f,'PHASE67_CANDIDATE_ISSUER_LISTING_NOT_ORIGINAL');
  });
  it('forged expiry in second catalog is not substituted into 1W or winning contract selection',()=>{
    const f=fixture();
    f.issuerMaster.snapshots[0].optionContracts[0].expiry='2026-02-18';
    f.updateMaster();f.repin();
    rejects(f,'PHASE67_CANDIDATE_ISSUER_LISTING_NOT_ORIGINAL');
  });
  it('dropping even one unselected PE contract invalidates entire decision-time issuer snapshot',()=>{
    const f=fixture();
    f.issuerMaster.snapshots[0].optionContracts.pop();
    f.updateMaster();f.repin();
    rejects(f,'PHASE67_ORIGINAL_LISTED_OOS_OPTION_SNAPSHOT_MISSING');
  });
  it('extra claimed issuer option not originally listed cannot be backfilled as an OOS choice',()=>{
    const f=fixture();
    f.issuerMaster.snapshots[0].optionContracts.push({
      ...f.issuerMaster.snapshots[0].optionContracts[0],
      instrumentKey:'FAKE_ADDITIONAL_OPTION'
    });
    f.updateMaster();f.repin();
    rejects(f,'PHASE67_ORIGINAL_LISTED_OOS_OPTION_SNAPSHOT_MISSING');
  });
  it('duplicate same-day snapshot cannot inflate original independent OOS fold',()=>{
    const f=fixture();
    f.issuerMaster.snapshots[1].originalDecisionAt=
      f.issuerMaster.snapshots[0].originalDecisionAt;
    f.issuerMaster.snapshots[1].originalOosSessionDate=
      f.issuerMaster.snapshots[0].originalOosSessionDate;
    f.updateMaster();f.repin();
    rejects(f,'PHASE67_MASTER_SNAPSHOT_BACKFILLED_OR_DUPLICATED');
  });
  it('contract master received after its decision cannot be used by the earlier strategy',()=>{
    const f=fixture();
    const snapshot=f.issuerMaster.snapshots[0];
    snapshot.claimedMasterReceivedAt=new Date(
      Date.parse(snapshot.originalDecisionAt)+60000).toISOString();
    f.updateMaster();f.repin();
    rejects(f,'PHASE67_MASTER_SNAPSHOT_BACKFILLED_OR_DUPLICATED');
  });
  it('individual claimed original listed instrument created only AFTER its master publication is noncausal',()=>{
    const f=fixture();
    const snapshot=f.issuerMaster.snapshots[0];
    snapshot.optionContracts[0].claimedFirstListedAt=
      new Date(Date.parse(snapshot.claimedMasterPublishedAt)+60000)
        .toISOString();
    f.updateMaster();f.repin();
    rejects(f,'PHASE67_CANDIDATE_EXPIRY_OR_LAST_TRADING_SESSION_INVALID');
  });
  it('self-provided calendar received after first original OOS decision cannot prove original next-session availability',()=>{
    const f=fixture();
    f.issuerCalendar.claimedCalendarReceivedAt='2026-04-20T00:00:00.000Z';
    f.updateCalendar();f.repin();
    rejects(f,'PHASE67_CLAIMED_CALENDAR_AVAILABLE_ONLY_AFTER_OOS_DECISION');
  });
  it('calendar mismatch in a single historical session time cannot make a fictitious next-open price',()=>{
    const f=fixture();
    f.issuerCalendar.sessions.find(s=>s.sessionDate==='2026-02-12')!
      .openAt='2026-02-12T03:50:00.000Z';
    f.updateCalendar();f.repin();
    rejects(f,'PHASE67_ORIGINAL_SESSION_CLOCK_DIFFERS_FROM_ISSUER_CANDIDATE');
  });
  it('missing following OOS session cannot make an unobserved overnight risk disappear',()=>{
    const f=fixture();
    f.issuerCalendar.sessions=f.issuerCalendar.sessions.filter(
      s=>s.sessionDate!=='2026-02-12');
    f.pins.expectedIssuerCalendarSessions--;
    f.updateCalendar();f.repin();
    rejects(f,'PHASE67_ORIGINAL_SESSION_CLOCK_DIFFERS_FROM_ISSUER_CANDIDATE');
  });
  it('last tradable date earlier than another claimed trading session before expiry must fail',()=>{
    const f=fixture();
    f.issuerMaster.snapshots[0].optionContracts[0]
      .claimedLastTradingSessionDate='2026-02-12';
    f.updateMaster();f.repin();
    rejects(f,'PHASE67_CANDIDATE_EXPIRY_OR_LAST_TRADING_SESSION_INVALID');
  });
  it('expiry cannot be before declared last tradable session, irrespective of locally supplied issuer pin',()=>{
    const f=fixture();
    const c=f.issuerMaster.snapshots[0].optionContracts[0];
    c.claimedLastTradingSessionDate='2026-02-17';
    f.updateMaster();f.repin();
    rejects(f,'PHASE67_CANDIDATE_EXPIRY_OR_LAST_TRADING_SESSION_INVALID');
  });
  it('a native L1 option print occurring AFTER claimed contract last-trading session cannot count as historical tradable price',()=>{
    const f=fixture();
    const quotes=f.vendor.raw;
    const c=f.issuerMaster.snapshots[0].optionContracts[0];
    const expiryPlusOne=new Date(Date.parse(
      c.expiry+'T00:00:00Z')+86400000)
        .toISOString().slice(0,10);
    // Expiry+1 is already separately listed for next-day candidate expiry
    // in the synthetic issuer calendar. This extra print is NOT part of
    // original decision-to-close / next-open coverage.
    assert.ok(f.issuerCalendar.sessions.some(
      s=>s.sessionDate===expiryPlusOne));
    const seq=quotes.length;
    const event=expiryPlusOne+'T04:30:00.000Z';
    quotes.push([
      'MOCK_L1_RECORD_'+seq,String(seq),c.instrumentKey,
      event,new Date(Date.parse(event)+5000).toISOString(),
      '100','101','100','100'
    ]);
    f.vendor.pins.expectedNativeQuoteRows++;
    f.vendor.updateQuotes();f.vendor.repinOuter();f.repin();
    const r=rejects(f,'PHASE67_ORIGINAL_L1_AFTER_CLAIMED_LAST_TRADABLE_EXPIRY');
    assert.equal(r.originalQuotesBeyondClaimedLastTradableSession,1);
  });
  it('source option BID/ASK coverage failing the earlier Phase66 gate cannot be rehabilitated by issuer-looking documents',()=>{
    const f=fixture();
    f.vendor.raw[1][7]='0';
    f.vendor.updateQuotes();f.vendor.repinOuter();f.repin();
    rejects(f,'PHASE66_ORIGINAL_FULL_LISTED_SOURCE_OR_FOLDS_NOT_READY');
  });
  it('missing original NO_ENTRY OOS date cannot be replaced with later issuer contract master records',()=>{
    const f=fixture();
    f.vendor.catalog.decisions.shift();
    f.vendor.updateCatalog();f.vendor.repinOuter();f.repin();
    rejects(f,'PHASE66_ORIGINAL_FULL_LISTED_SOURCE_OR_FOLDS_NOT_READY');
  });
  it('different self-claimed issuer ID even after repinning documents remains descriptive ONLY, never authenticated exchange',()=>{
    const f=fixture();
    const claimed='OTHER_SELF_CLAIMED_EXCHANGE_ISSUER';
    f.issuerMaster.claimedIssuerReference=claimed;
    f.issuerCalendar.claimedIssuerReference=claimed;
    f.pins.expectedClaimedIssuerReference=claimed;
    f.updateMaster();f.updateCalendar();f.repin();
    const r=audit(f);noAuthentication(r);
    assert.equal(r.status,'DESCRIPTIVE_CROSS_SOURCE_MATCH_UNVERIFIED_ONLY',
      JSON.stringify(r));
    assert.equal(r.independentlyAuthenticatedExchangeMasterIssuer,false);
  });
});
